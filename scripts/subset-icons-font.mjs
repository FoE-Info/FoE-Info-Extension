#!/usr/bin/env node
/**
 * Rebuild the Material Symbols subset from the icons the source actually uses.
 *
 * The shipped font is a variable font with 6,607 glyphs (3.9 MB) and the panel
 * uses one. This subsets to the names found in src/ and refuses to write the
 * result unless every name still resolves to a real glyph in the output — a
 * silently dropped ligature renders as the literal text "content_copy" in the
 * copy button, which is obvious in the UI but not in a diff.
 *
 * Idempotent: always reads from the pristine full-size source and writes to the
 * subset output, so running it N times yields the same bytes as running it once.
 *
 * Run: npm run fonts:subset
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src', 'js');
const FONT_DIR = path.join(ROOT, 'src', 'fonts');
/** Pristine full-size upstream font — never overwritten by this script. */
const FONT_SRC = path.join(
  FONT_DIR,
  'MaterialSymbolsOutlined-Regular-full.woff2',
);
const FONT = path.join(FONT_DIR, 'MaterialSymbolsOutlined-Regular.woff2');
const MANIFEST = path.join(FONT_DIR, 'icons-subset.json');
const CLASS = 'material-symbols-outlined';

/** Every .js under a directory, recursively. */
function jsFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...jsFiles(full));
    else if (/\.(?:js|mjs|cjs)$/.test(entry.name)) out.push(full);
  }
  return out;
}

/**
 * Icon names are the element text of a span carrying the symbols class:
 *   <span class="... material-symbols-outlined" ...>content_copy</span>
 * The class and its text can sit on different lines, so match across newlines
 * and keep the search window tight to avoid running into a later span.
 */
function findIconNames(source) {
  const names = new Set();
  const re = new RegExp(`${CLASS}[\\s\\S]{0,600}?>([a-z0-9_]+)<`, 'g');
  for (const m of source.matchAll(re)) names.add(m[1]);
  return names;
}

function uvx(args) {
  return execFileSync('uvx', args, { cwd: ROOT, encoding: 'utf8' });
}

const names = [
  ...new Set(
    jsFiles(SRC).flatMap((f) => [...findIconNames(fs.readFileSync(f, 'utf8'))]),
  ),
].sort();

if (names.length === 0) {
  console.error(
    `No ${CLASS} icons found under src/js. The markup shape probably changed; ` +
      'update findIconNames() before regenerating the subset.',
  );
  process.exit(1);
}

if (!fs.existsSync(FONT_SRC)) {
  console.error(
    `Full upstream font not found: ${path.relative(ROOT, FONT_SRC)}\n` +
      'This file must be committed as source. Recover it from git history:\n' +
      '  git show a446fd4~1:src/fonts/MaterialSymbolsOutlined-Regular.woff2 > ' +
      path.relative(ROOT, FONT_SRC),
  );
  process.exit(1);
}

const srcSize = fs.statSync(FONT_SRC).size;
const tmp = path.join(FONT_DIR, '.subset-candidate.woff2');

uvx([
  '--from',
  'fonttools[woff]==4.66.1',
  'pyftsubset',
  FONT_SRC,
  `--text=${names.join(',')}`,
  '--layout-features=*',
  '--flavor=woff2',
  `--output-file=${tmp}`,
  '--name-IDs=*',
  '--name-legacy',
  '--name-languages=*',
]);

// Refuse to ship a subset that lost an icon. The name is shaped by a required
// ligature (rlig), not by cmap, so this is the only check that proves the glyph
// survived — a file-size comparison would not.
const verifier = path.join(ROOT, 'scripts', 'lib', 'verify-icon-font.py');
uvx(['--from', 'fonttools[woff]==4.66.1', 'python', verifier, tmp, ...names]);

fs.renameSync(tmp, FONT);
fs.writeFileSync(
  MANIFEST,
  JSON.stringify(
    {
      note: 'Generated by scripts/subset-icons-font.mjs (npm run fonts:subset). Do not hand-edit.',
      source: path.relative(ROOT, FONT_SRC),
      class: CLASS,
      icons: names,
    },
    null,
    2,
  ) + '\n',
);

const subsetSize = fs.statSync(FONT).size;
const pct = ((1 - subsetSize / srcSize) * 100).toFixed(1);
console.log(`icons:     ${names.join(', ')}`);
console.log(
  `font:      ${srcSize.toLocaleString()} -> ${subsetSize.toLocaleString()} bytes (-${pct}%)`,
);
console.log(`manifest:  ${path.relative(ROOT, MANIFEST)}`);
