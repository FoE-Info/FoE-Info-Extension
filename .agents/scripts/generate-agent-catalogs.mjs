#!/usr/bin/env node

import {
  closeSync,
  openSync,
  readFileSync,
  readdirSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const AGENTS_ROOT = join(PROJECT_ROOT, '.agents');
const CHECK_ONLY = process.argv.includes('--check');

function frontmatter(file) {
  const content = readFileSync(file, 'utf8');
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) throw new Error(`Missing frontmatter: ${relative(PROJECT_ROOT, file)}`);
  const field = (key) => {
    const found = match[1].match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
    if (!found) throw new Error(`Missing ${key}: ${relative(PROJECT_ROOT, file)}`);
    return found[1].trim().replace(/^["']|["']$/g, '');
  };
  return { name: field('name'), description: field('description') };
}

function skillRows() {
  const root = join(AGENTS_ROOT, 'skills');
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const definition = frontmatter(join(root, entry.name, 'SKILL.md'));
      if (definition.name !== entry.name) {
        throw new Error(`Skill name mismatch: ${entry.name} != ${definition.name}`);
      }
      return definition;
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function agentRows() {
  const root = join(AGENTS_ROOT, 'agents');
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => {
      const definition = frontmatter(join(root, entry.name));
      const expected = entry.name.replace(/\.md$/, '');
      if (definition.name !== expected) {
        throw new Error(`Subagent name mismatch: ${expected} != ${definition.name}`);
      }
      return definition;
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function table(rows) {
  return [
    '| Name | Purpose |',
    '| --- | --- |',
    ...rows.map(({ name, description }) => `| \`${name}\` | ${description} |`),
  ].join('\n');
}

function skillsDocument(rows) {
  return `# Skills & Runbooks Catalog (${rows.length} skills)\n\n<!-- generated by .agents/scripts/generate-agent-catalogs.mjs; do not edit by hand -->\n\nCanonical definitions live under \`.agents/skills/<name>/SKILL.md\`. Harnesses should select and load a skill only when its frontmatter description matches the task.\n\n${table(rows)}\n\n## Supporting knowledge\n\nShared domain knowledge and worked examples live in [the reference catalog](../.agents/references/README.md).\n`;
}

function agentsDocument(rows) {
  return `# Subagent Delegation Catalog (${rows.length} subagents)\n\n<!-- generated by .agents/scripts/generate-agent-catalogs.mjs; do not edit by hand -->\n\nCanonical personas live under \`.agents/agents/<name>.md\`; OpenCode shims mirror those names under \`.opencode/agents/\`. Use a subagent for an independently delegated role with a bounded deliverable.\n\n${table(rows)}\n\nSee [the routing table](../.agents/references/subagent-routing.md) for task-to-role selection and profile requirements.\n`;
}

function removeOwnedTemp(temp, suppressError) {
  try {
    unlinkSync(temp);
  } catch (error) {
    if (error?.code !== 'ENOENT' && !suppressError) throw error;
  }
}

function atomicWrite(file, content) {
  const temp = `${file}.catalog-${process.pid}-${randomBytes(8).toString('hex')}.tmp`;
  let descriptor;
  try {
    descriptor = openSync(temp, 'wx', 0o600);
    writeFileSync(descriptor, content, 'utf8');
    closeSync(descriptor);
    descriptor = undefined;
    renameSync(temp, file);
  } catch (error) {
    if (descriptor !== undefined) {
      try {
        closeSync(descriptor);
      } catch {
        // Preserve the original write/close/rename failure.
      }
    }
    removeOwnedTemp(temp, true);
    throw error;
  }
  removeOwnedTemp(temp, false);
}

async function formatted(file, content) {
  const config = (await resolveConfig(file)) ?? {};
  return format(content, { ...config, filepath: file });
}

const skillsFile = join(PROJECT_ROOT, 'docs', 'SKILLS.md');
const agentsFile = join(PROJECT_ROOT, 'docs', 'SUBAGENTS.md');
const outputs = [
  [skillsFile, await formatted(skillsFile, skillsDocument(skillRows()))],
  [agentsFile, await formatted(agentsFile, agentsDocument(agentRows()))],
];

let stale = false;
for (const [file, expected] of outputs) {
  const current = readFileSync(file, 'utf8');
  if (current === expected) continue;
  stale = true;
  if (!CHECK_ONLY) atomicWrite(file, expected);
  else process.stderr.write(`Stale generated catalog: ${relative(PROJECT_ROOT, file)}\n`);
}

if (CHECK_ONLY && stale) process.exitCode = 1;
else process.stdout.write(`${CHECK_ONLY ? 'Current' : 'Generated'} ${outputs.length} catalogs\n`);
